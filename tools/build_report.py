def bullets(items, size=14):
    for item in items:
        par = doc.add_paragraph(style='List Bullet')
        par.paragraph_format.first_line_indent = Cm(1.25)
        par.paragraph_format.line_spacing = 1.5
        par.paragraph_format.space_after = Pt(0)
        par.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        run = par.add_run(item)
        run.font.name = FONT
        run.font.size = Pt(size)


def numbered(items, size=14):
    for index, item in enumerate(items, start=1):
        par = doc.add_paragraph()
        par.paragraph_format.first_line_indent = Cm(1.25)
        par.paragraph_format.line_spacing = 1.5
        par.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        run = par.add_run(f'{index}) {item}')
        run.font.name = FONT
        run.font.size = Pt(size)


def caption(text, before=6, after=6):
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.first_line_indent = Cm(0)
    par.paragraph_format.space_before = Pt(before)
    par.paragraph_format.space_after = Pt(after)
    par.paragraph_format.line_spacing = 1.5
    run = par.add_run(text)
    run.font.name = FONT
    run.font.size = Pt(12)
    return par


def figure(name, number, title, width_cm=16, note=None):
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.first_line_indent = Cm(0)
    par.paragraph_format.space_before = Pt(6)
    par.paragraph_format.space_after = Pt(4)
    par.add_run().add_picture(os.path.join(IMG, name), width=Cm(width_cm))
    caption(f'Рисунок {number} — {title}', before=0, after=8)
    if note:
        p(note)


def _cell_text(cell, text, size=12, bold=False, align='left'):
    cell.text = ''
    par = cell.paragraphs[0]
    par.alignment = {'left': WD_ALIGN_PARAGRAPH.LEFT,
                     'center': WD_ALIGN_PARAGRAPH.CENTER,
                     'justify': WD_ALIGN_PARAGRAPH.JUSTIFY}[align]
    par.paragraph_format.first_line_indent = Cm(0)
    par.paragraph_format.line_spacing = 1.0
    par.paragraph_format.space_after = Pt(2)
    par.paragraph_format.space_before = Pt(2)
    run = par.add_run(text)
    run.font.name = FONT
    run.font.size = Pt(size)
    run.bold = bold


def table(number, title, headers, rows, widths=None, size=11, align='left'):
    caption(f'Таблица {number} — {title}', before=8, after=4)
    tbl = doc.add_table(rows=1, cols=len(headers))
    tbl.style = 'Table Grid'
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    for index, header in enumerate(headers):
        _cell_text(tbl.rows[0].cells[index], header, size=size, bold=True,
                   align='center')
    for row in rows:
        cells = tbl.add_row().cells
        for index, value in enumerate(row):
            _cell_text(cells[index], str(value), size=size, align=align)
    if widths:
        tbl.autofit = False
        for row in tbl.rows:
            for index, width in enumerate(widths):
                row.cells[index].width = Cm(width)
    # повтор шапки на новой странице
    tr_pr = tbl.rows[0]._tr.get_or_add_trPr()
    tbl_header = OxmlElement('w:tblHeader')
    tbl_header.set(qn('w:val'), 'true')
    tr_pr.append(tbl_header)
    doc.add_paragraph().paragraph_format.space_after = Pt(6)
    return tbl


def listing(number, title, code, size=9):
    caption(f'Листинг {number} — {title}', before=8, after=4)
    for line in code.strip('\n').split('\n'):
        par = doc.add_paragraph()
        par.paragraph_format.first_line_indent = Cm(0)
        par.paragraph_format.left_indent = Cm(0.5)
        par.paragraph_format.line_spacing = 1.0
        par.paragraph_format.space_after = Pt(0)
        par.paragraph_format.space_before = Pt(0)
        run = par.add_run(line if line.strip() else ' ')
        run.font.name = MONO
        run.font.size = Pt(size)
    doc.add_paragraph().paragraph_format.space_after = Pt(4)


