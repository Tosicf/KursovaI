def contents():
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.first_line_indent = Cm(0)
    par.paragraph_format.space_after = Pt(12)
    run = par.add_run('ОГЛАВЛЕНИЕ')
    run.font.name = FONT
    run.font.size = Pt(14)
    run.bold = True
    par = doc.add_paragraph()
    par.paragraph_format.first_line_indent = Cm(0)
    par.paragraph_format.line_spacing = 1.5

    run = par.add_run()
    fld_begin = OxmlElement('w:fldChar')
    fld_begin.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText')
    instr.set(qn('xml:space'), 'preserve')
    instr.text = 'TOC \\o "1-2" \\h \\z \\u'
    fld_sep = OxmlElement('w:fldChar')
    fld_sep.set(qn('w:fldCharType'), 'separate')
    fld_end = OxmlElement('w:fldChar')
    fld_end.set(qn('w:fldCharType'), 'end')
    run._r.append(fld_begin)
    run._r.append(instr)
    run._r.append(fld_sep)

    placeholder = par.add_run(
        'Оглавление формируется автоматически: при открытии документа Word '
        'обновит поле, при необходимости нажмите Ctrl+A и F9.')
    placeholder.font.name = FONT
    placeholder.font.size = Pt(12)
    placeholder.italic = True

    end_run = par.add_run()
    end_run._r.append(fld_end)

    p('', indent=False)
    p('Примечание: оглавление построено как поле Word (TOC). Если в вашей версии '
      'Word оно не обновилось автоматически, установите курсор в область '
      'оглавления и нажмите F9, выбрав «Обновить целиком».', indent=False, size=11,
      italic=True)


