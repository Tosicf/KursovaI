def _cover(text, size=14, bold=False, align='center', after=0, before=0, spacing=1.0):
    """Строка титульного листа: без отступа первой строки, точный интервал."""
    return pz.p(text, indent=False, align=align, size=size, bold=bold,
                before=before, after=after, spacing=spacing)


def _blank(n=1):
    for _ in range(n):
        pz.p('', indent=False, spacing=1.0)


def _sign_block(left, right):
    """Две колонки без рамок: слева — кто подписывает, справа — линия и ФИО."""
    tbl = pz.doc.add_table(rows=1, cols=2)
    tbl.alignment = WD_TABLE_ALIGNMENT.LEFT
    tbl.autofit = False
    for cell, width in zip(tbl.rows[0].cells, (Cm(8.6), Cm(7.9))):
        cell.width = width
    for cell, lines, align in zip(tbl.rows[0].cells, (left, right),
                                  (WD_ALIGN_PARAGRAPH.LEFT, WD_ALIGN_PARAGRAPH.CENTER)):
        cell.text = ''
        first = True
        for text, size, bold in lines:
            par = cell.paragraphs[0] if first else cell.add_paragraph()
            first = False
            par.alignment = align
            pf = par.paragraph_format
            pf.first_line_indent = Cm(0)
            pf.space_before = Pt(0)
            pf.space_after = Pt(0)
            pf.line_spacing = 1.0
            run = par.add_run(text)
            run.font.name = 'Times New Roman'
            run.font.size = Pt(abs(size))
            run.bold = bold
    pz.doc.add_paragraph().paragraph_format.line_spacing = 1.0


